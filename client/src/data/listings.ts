import type { ListingRecord } from './data';
import { photoUrl, type PhotoKey } from './photos';

type Seed = Omit<ListingRecord, 'photos'> & {
  hero: PhotoKey[];
  tour: { name: string; description: string; photos: PhotoKey[] };
};

function make({ hero, tour, ...rest }: Seed): ListingRecord {
  return {
    ...rest,
    photos: {
      hero: { primary: photoUrl(hero[0]!), photos: hero.slice(0, 4).map(photoUrl) },
      tour: {
        name: tour.name,
        description: tour.description,
        photos: tour.photos.map(photoUrl),
        primary: photoUrl(tour.photos[0] ?? hero[0]!),
      },
    },
  };
}

